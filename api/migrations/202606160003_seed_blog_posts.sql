## The Five Documents That Matter

When someone is selling land in Delta State, ask for all five of these. If they cannot produce them, walk away.

### 1. Certificate of Occupancy (C of O)

This is the strongest title document in Nigeria. It is issued by the state government and proves that the holder has a right of occupancy over the land.

What to check on a C of O:
- The name on the document must match the seller''s name (or there must be a valid Deed of Assignment showing how ownership transferred)
- The survey plan number on the C of O must match a physical survey of the land
- Check the expiry date — C of Os in Delta State are typically for 99 years

Take the C of O to the Delta State Ministry of Lands in Asaba to confirm it is genuine and not revoked.

### 2. Deed of Assignment

If the land has changed hands since the original C of O was issued, there should be a Deed of Assignment for each transfer. This is the document that transfers interest from one person to another.

A Deed of Assignment must be:
- Signed by both parties (seller and buyer)
- Stamped by a lawyer
- Registered at the Land Registry

If there are multiple past owners, there should be a chain of Deeds going back to the original C of O holder.

### 3. Survey Plan

The survey plan shows the exact boundaries of the land. It is drawn by a licensed surveyor and has a beacon number.

Take the survey plan number to the Delta State Office of the Surveyor General in Asaba. They can confirm whether the plan is genuine and whether the land falls within a government acquisition area.

Never buy land without a verified survey plan. Many scams in Warri involve land in acquisition areas where the government has already taken over the ground.

### 4. Governor''s Consent

Under the Land Use Act, any transfer of land title in Nigeria requires the Governor''s Consent. Without it, the transfer is technically incomplete.

When you buy land with a C of O, you need Governor''s Consent to register the new Deed of Assignment in your name. This process costs money and takes time, but it is what gives you a clean, registered title.

### 5. Receipt and Agreement of Sale

Even before the formal documents are transferred, there should be a signed Agreement of Sale. This is not a title document, but it protects you while the main transfer is being processed.

