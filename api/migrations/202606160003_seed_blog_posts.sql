**Office of the Surveyor General, Asaba** — Verify survey plans and check acquisition lists here.

**A Registered Lawyer** — Do not use any lawyer the seller recommends. Find your own. A good property lawyer in Delta State charges between ₦50,000 and ₦150,000 for a full land search and document review. That is cheap compared to losing your money.

